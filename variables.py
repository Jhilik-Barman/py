# ==========================================
# Python Variables - Complete Basic Example
# ==========================================

# 1. String Variable
# A string variable is used to store text.
name = "Rahul"


# 2. Integer Variable
# An integer variable is used to store a whole number.
age = 21


# 3. Float Variable
# A float variable is used to store a decimal number.
salary = 25000.50


# 4. Boolean Variable
# A boolean variable stores either True or False.
is_student = True


# 5. Multiple Variables
# We can create multiple variables in a program.
city = "Kolkata"
country = "India"


# 6. Printing Variables
# We can use the print() function to display variable values.
print("Name:", name)
print("Age:", age)
print("Salary:", salary)
print("Is Student:", is_student)
print("City:", city)
print("Country:", country)


# 7. Performing Calculation with Variables
# We can use variables to perform mathematical calculations.
bonus = 5000

total_salary = salary + bonus

print("Bonus:", bonus)
print("Total Salary:", total_salary)


# 8. Updating a Variable
# We can change the value of a variable at any time.
age = 22

print("Updated Age:", age)


# 9. Using Variables in a Calculation
# Variables can be used with mathematical operators.
number1 = 10
number2 = 20

addition = number1 + number2
subtraction = number2 - number1
multiplication = number1 * number2
division = number2 / number1

print("Addition:", addition)
print("Subtraction:", subtraction)
print("Multiplication:", multiplication)
print("Division:", division)


# 10. Checking Variable Data Types
# The type() function tells us the data type of a variable.
print("Name Type:", type(name))
print("Age Type:", type(age))
print("Salary Type:", type(salary))
print("Student Type:", type(is_student))


# 11. Creating Variables with the Same Value
# Multiple variables can have the same value.
x = y = z = 100

print("X:", x)
print("Y:", y)
print("Z:", z)


# 12. Creating Multiple Variables in One Line
# We can assign different values to different variables in one line.
first_name, last_name, age = "Rahul", "Sharma", 25

print("First Name:", first_name)
print("Last Name:", last_name)
print("Age:", age)


